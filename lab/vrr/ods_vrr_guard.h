static inline bool ods_vrr_identity(bool opt_in, bool internal,
                                    const unsigned char *edid, unsigned size)
{
    unsigned i;
    if (!opt_in || !internal || !edid || size != sizeof(ods_r04_edid))
        return false;
    for (i = 0; i < sizeof(ods_r04_edid); i++)
        if (edid[i] != ods_r04_edid[i])
            return false;
    return true;
}
static inline bool ods_vrr_native(unsigned clock, unsigned ha, unsigned hss,
                                  unsigned hse, unsigned ht, unsigned skew,
                                  unsigned va, unsigned vss, unsigned vse,
                                  unsigned vt, unsigned scan, unsigned flags)
{
    return clock == 143180 && ha == 1080 && hss == 1112 && hse == 1120 &&
        ht == 1220 && skew == 0 && va == 1920 && vss == 1928 && vse == 1930 &&
        vt == 1956 && scan == 0 && flags == 5;
}
static inline bool ods_vrr_adjust_allowed(unsigned min, unsigned max,
                                          unsigned mid, unsigned mid_frames,
                                          bool halt)
{
    return !halt && !mid && !mid_frames &&
        ((min == 1956 && max == 1956) ||
         (min == ODS_VRR_MIN_TOTAL && max == ODS_VRR_MAX_TOTAL));
}
